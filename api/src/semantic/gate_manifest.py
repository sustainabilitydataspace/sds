def gates_by_slice() -> dict[str, list[GateSpec]]:
    """Gates grouped by slice, in progressive SLICE_ORDER."""
    grouped: dict[str, list[GateSpec]] = {s: [] for s in SLICE_ORDER}
    for gate in VARCH_GATES:
        grouped.setdefault(gate.slice, []).append(gate)
    return grouped
