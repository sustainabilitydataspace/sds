"""VARCH gate manifest (VARCH-10).

The single registry of the progressive CI gates the VARCH-0..9 slices contribute. Each gate is a
named, documented contract whose mechanism lives in a semantic module and whose enforcement lives
in a contract test. The manifest is SELF-VERIFYING: ``test_varch10_gate_manifest`` asserts every
``verify`` token actually appears in the gate's module/test source, so the registry can never
silently drift from the code. The ``scripts/gate_varch.py`` runner consumes this manifest to run
the gates progressively (slice order) with per-gate observability.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class GateSpec:
    """One progressive CI gate: a named contract, its module, and its enforcing test."""

    name: str
    slice: str
    module: str  # repo-relative path whose docstring documents the mechanism
    test: str  # repo-relative pytest path that enforces it
    contract: str
    # MANDATORY token that MUST appear in the gate's module+test source — the self-verification
    # mechanism that keeps the manifest from drifting from the code (no empty/structural escape).
    verify: str


